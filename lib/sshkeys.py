"""The host's SSH keys inside a container (`[ssh] copy_keys`, host profile).

Some tools offer only key FILES in ~/.ssh and never ask the forwarded agent:
`gh auth login` then proposes to generate a new key. With copy_keys on, `dck
up` binds the host's ~/.ssh read-only at ~/.ssh_host through a runtime compose
overlay (never written into the repository), and the entrypoint copies its
`id_*` keys into the container's ~/.ssh on every start (lib/entrypoint.sh,
dck_ssh_copy_keys). Off by default; a repository's dck.toml cannot turn it on.

Only file NAMES are ever read here or printed — never a key's contents.
"""

import json
import os
import re

# The names the entrypoint copies: id_<anything safe>, private keys and .pub.
RE_KEY_NAME = re.compile(r"^id_[A-Za-z0-9._-]+$")
MANIFEST = ".dck-copied-keys"


class SshKeysError(Exception):
    pass


def container_home(user):
    return "/root" if user == "root" else "/home/%s" % user


def host_ssh_dir(env=None):
    env = os.environ if env is None else env
    return os.path.join(env.get("HOME", ""), ".ssh")


def key_names(d):
    """The id_* regular files (never a symlink) of a directory, sorted."""
    try:
        names = os.listdir(d)
    except OSError:
        return []
    return sorted(n for n in names if RE_KEY_NAME.match(n)
                  and os.path.isfile(os.path.join(d, n)) and not os.path.islink(os.path.join(d, n)))


def plan(merged, env=None):
    """What `dck up` would bind, and the key names the entrypoint would copy."""
    env = os.environ if env is None else env
    home = container_home(merged["user"])
    src = host_ssh_dir(env)
    out = {"enabled": False, "reason": "", "source": src, "target": home + "/.ssh_host",
           "manifest": home + "/.ssh/" + MANIFEST, "host_keys": []}
    if not merged.get("ssh_copy_keys"):
        out["reason"] = "off ([ssh] copy_keys in the host profile); only the forwarded agent signs"
        return out
    if not os.path.isdir(src):
        out["reason"] = "copy_keys is on, but the host has no %s" % src
        return out
    out["enabled"] = True
    out["source"] = os.path.realpath(src)
    out["host_keys"] = key_names(out["source"])
    return out


def _write_private(path, text):
    d = os.path.dirname(path)
    old = os.umask(0o077)
    try:
        os.makedirs(d, 0o700, exist_ok=True)
    finally:
        os.umask(old)
    if os.path.islink(d) or not os.path.isdir(d) or os.stat(d).st_uid != os.getuid():
        raise SshKeysError("%s is not a directory you own; refusing to write there" % d)
    tmp = "%s.tmp-%d" % (path, os.getpid())
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.replace(tmp, path)


def write(merged, service, out_path, env=None):
    """Write the runtime overlay when on, remove it when off. Returns the plan."""
    p = plan(merged, env)
    if not p["enabled"]:
        try:
            if os.path.islink(out_path) or os.path.isfile(out_path):
                os.unlink(out_path)
        except OSError:
            pass
        return p
    if not re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$", service):
        raise SshKeysError("invalid service name %r" % service)
    if any(ord(c) < 32 for c in p["source"] + p["target"]):
        raise SshKeysError("refusing a path with control characters")
    lines = ["# Generated by dck at runtime for [ssh] copy_keys — never written into the",
             "# repository. Names a host path only; no key is in this file.",
             "services:", "  %s:" % service,
             "    environment:",
             "      DCK_SSH_COPY_KEYS: \"1\"",
             "    volumes:",
             "      - type: bind",
             "        source: %s" % json.dumps(p["source"].replace("$", "$$")),
             "        target: %s" % json.dumps(p["target"]),
             "        read_only: true",
             "        bind:",
             "          create_host_path: false"]
    _write_private(out_path, "\n".join(lines) + "\n")
    return p


def parse_manifest(text):
    """Key names from the container's manifest; anything else is dropped."""
    return sorted(set(n.strip() for n in (text or "").splitlines() if RE_KEY_NAME.match(n.strip())))
