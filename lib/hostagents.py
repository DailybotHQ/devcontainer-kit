"""The host's agent accounts inside a container (`[agents] host_profiles`).

When the host profile turns it on, `dck up` shares with the container, through
a runtime compose overlay written outside the repository:

- each host coding-agents-kit profile of the CLIs the repository installs
  (`[agents] clis`), bound one by one under the container's profiles
  directory, which AGENTKIT_PROFILES_DIR then names. `[agents]
  host_profile_names` narrows them to the ones listed ("claude@work1",
  "codex@default", ...). Only file-portable isolations are shared; cursor (and
  antigravity) profiles hold absolute host symlinks and are skipped. The whole
  AGENTKIT_HOME is never mounted: it would shadow the ak the image pins;
- the host's Codex home (`$CODEX_HOME`, else `~/.codex`: the Codex @default
  login) when codex @default is shared;
- an env file generated on the host, its per-project directory mounted
  read-only with AGENTKIT_ENV pointing at the file inside (the directory, not
  the file, so a rewrite on the next `dck up` reaches a running container). It holds no implicit secret: only the Claude token of each
  Claude profile actually shared (CLAUDE_CODE_OAUTH_TOKEN for @default,
  CLAUDE_CODE_OAUTH_TOKEN_<SUFFIX> for @name) and the exact names listed in
  `[agents] host_env_keys`.

Least privilege: a mount is read-write only where the CLI must write (MOUNT
MODES below, each with its reason, shown by the doctor and documented in
docs/SECURITY.md); everything else is read-only. Values never leave the env
file: the overlay, the logs and `dck doctor` name variables only. Interface
from coding-agents-kit v0.5.0: the Claude token per profile, and `ak profiles
--json` (schema profiles-v1).
"""

import json
import os
import re
import subprocess

import config

# Isolations whose profile directories are plain files, portable into a container.
SHAREABLE = ("claude", "codex", "pi", "cline", "grok", "opencode")
NOT_PORTABLE = {
    "cursor": "its profiles hold absolute host symlinks (a HOME of their own)",
    "antigravity": "its profiles hold absolute host symlinks (a HOME of their own)",
}
# Mount mode of each shared directory, with the reason. Read-write only where the
# CLI writes; docs/SECURITY.md carries the same table (checked by the tests).
MOUNT_MODES = {
    "claude": ("rw", "Claude rewrites its profile state (.claude.json, settings, sessions, history) on every run"),
    "codex": ("rw", "Codex refreshes its login in auth.json and writes sessions and history"),
    "pi": ("rw", "pi writes its sessions and settings in its home"),
    "cline": ("rw", "Cline writes its task state and settings in its home"),
    "grok": ("rw", "grok writes its sessions and settings and refreshes its login in its home"),
    "opencode": ("rw", "opencode writes its sessions and data and refreshes provider logins (auth.json)"),
    "env": ("ro", "generated by dck on the host; nothing in the container writes it"),
}
PROFILES_SCHEMA = "profiles-v1"
RE_PROFILE_DIR = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class HostAgentsError(Exception):
    pass


def profiles_dir(env):
    return env.get("AGENTKIT_PROFILES_DIR") or os.path.join(
        env.get("HOME", ""), ".local", "share", "agentkit", "profiles")


def codex_home(env):
    return env.get("CODEX_HOME") or os.path.join(env.get("HOME", ""), ".codex")


def ak_env_path(env):
    return env.get("AGENTKIT_ENV") or os.path.join(env.get("HOME", ""), ".config", "agentkit", "env")


def env_dir_path(project, env=None):
    """The directory holding one compose project's env file on the host. The
    directory is what gets bound, never the file: the file is replaced
    atomically (a new inode) on every `dck up`, and a single-file bind would
    keep showing the old one inside a running container."""
    env = os.environ if env is None else env
    if not re.match(r"^[a-z0-9][a-z0-9_-]*$", project or ""):
        raise HostAgentsError("invalid compose project name %r" % project)
    return os.path.join(config.config_home(env), "agents", project)


def env_file_path(project, env=None):
    """Where the env file of one compose project lives on the host."""
    return os.path.join(env_dir_path(project, env), "env")


def legacy_env_file_path(project, env=None):
    """The single-file location used up to v0.3.0, removed on sight."""
    return env_dir_path(project, env) + ".env"


def read_env_file(path):
    """The KEY=value subset of an ak env file (`export` allowed, values in
    quotes or bare, # comments), as coding-agents-kit reads it without a
    shell. Nothing is expanded or executed; shell code is ignored."""
    try:
        with open(path) as fh:
            lines = fh.read().splitlines()
    except OSError:
        return {}
    out = {}
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        name, sep, value = line.partition("=")
        name = name.strip()
        if not sep or not _NAME.match(name):
            continue
        value = value.strip()
        if value[:1] in ("'", '"') and value[0] in value[1:]:
            value = value[1:value.index(value[0], 1)]
        elif value[:1] in ("'", '"'):
            continue  # an unterminated quote is shell, not data
        elif " #" in value:
            value = value.split(" #", 1)[0].rstrip()
        if "$" in value or "`" in value:
            continue  # an expansion: shell code, not plain data
        out[name] = value
    return out


def _plain(value):
    return not any(c in value for c in ("'", "\n", "\r", "\x00"))


def container_home(user):
    return "/root" if user == "root" else "/home/%s" % user


def claude_token_var(profile):
    """The token variable of a Claude profile: @default or a name (suffix
    upper-cased, every character outside [A-Z0-9_] replaced by _)."""
    if not profile or profile in ("@default", "default"):
        return "CLAUDE_CODE_OAUTH_TOKEN"
    name = profile[1:] if profile.startswith("@") else profile
    return "CLAUDE_CODE_OAUTH_TOKEN_" + re.sub(r"[^A-Z0-9_]", "_", name.upper())


def plan(merged, env=None):
    """What `dck up` would share. Pure apart from reading the host's files.
    The returned "values" entry holds secret values: never print it."""
    env = os.environ if env is None else env
    home = container_home(merged["user"])
    base = home + "/.dck/host"
    out = {"enabled": False, "reason": "", "shared": [], "skipped": [], "codex": None,
           "env_names": [], "env_skipped": [], "values": {}, "profiles_root": profiles_dir(env),
           "ak_env": ak_env_path(env), "container_profiles": base + "/agentkit/profiles",
           "container_env_dir": base + "/agentkit/hostenv",
           "container_env": base + "/agentkit/hostenv/env", "container_codex": base + "/codex",
           "selected": list(merged.get("host_profile_names") or []),
           "defaults": [], "defaults_skipped": []}
    if not merged.get("host_profiles"):
        out["reason"] = "off ([agents] host_profiles in the host profile); nothing is shared or copied"
        return out
    if not merged.get("layers.agents"):
        out["reason"] = "host_profiles is on, but this repository's layers.agents is false; nothing is shared"
        return out
    out["enabled"] = True
    selected = set(out["selected"])

    def wanted(cli, name):
        return not selected or ("%s@%s" % (cli, name)) in selected

    root = out["profiles_root"]
    # Every SUPPORTED CLI (v0.3.6: dck.toml [agents] supported), installed or not:
    # a CLI a developer installs later finds its profiles. Only profiles that
    # exist on the host are bound.
    clis = merged.get("clis_supported")
    if clis is None:
        clis = merged.get("agents.clis") or []
    # What is skipped is reported for the CLIs this image installs; a supported
    # CLI nobody installs and nobody has profiles for is not news.
    requested = merged.get("clis_effective")
    requested = clis if requested is None else requested

    def skip(cli, why):
        if cli in requested:
            out["skipped"].append((cli, why))

    for cli in clis:
        if cli in NOT_PORTABLE:
            skip(cli, NOT_PORTABLE[cli])
            continue
        if cli not in SHAREABLE:
            skip(cli, "not a shareable kind")
            continue
        d = os.path.join(root, cli)
        names = sorted(n for n in (os.listdir(d) if os.path.isdir(d) else [])
                       if RE_PROFILE_DIR.match(n) and n != "default" and os.path.isdir(os.path.join(d, n))
                       and wanted(cli, n))
        mode, why = MOUNT_MODES[cli]
        for n in names:
            out["shared"].append({"cli": cli, "profile": "@" + n, "source": os.path.realpath(os.path.join(d, n)),
                                  "target": "%s/%s/%s" % (out["container_profiles"], cli, n),
                                  "mode": mode, "why": why})
        if not names:
            skip(cli, "no %sak profiles in %s" % ("selected " if selected else "", d))
    if "codex" in clis and wanted("codex", "default"):
        ch = codex_home(env)
        if os.path.isdir(ch):
            mode, why = MOUNT_MODES["codex"]
            out["codex"] = {"source": os.path.realpath(ch), "target": out["container_codex"],
                            "mode": mode, "why": why}
    # No implicit secret: the token of each Claude profile actually shared, and
    # the exact names the host profile lists.
    names = []
    if "claude" in clis and wanted("claude", "default"):
        names.append("CLAUDE_CODE_OAUTH_TOKEN")
    names += [claude_token_var(s["profile"]) for s in out["shared"] if s["cli"] == "claude"]
    names += [n for n in (merged.get("host_env_keys") or []) if n not in names]
    source = dict((k, env[k]) for k in names if k in env)
    source.update((k, v) for k, v in read_env_file(out["ak_env"]).items() if k in names)
    for name in names:
        if name not in source:
            out["env_skipped"].append((name, "not set on the host"))
        elif not source[name]:
            out["env_skipped"].append((name, "empty"))
        elif not _plain(source[name]):
            out["env_skipped"].append((name, "not a single-line value without quotes"))
        else:
            out["values"][name] = source[name]
            out["env_names"].append(name)
    # [agents] default_profile: only a profile actually shared can be a container's default.
    shared = set("%s%s" % (x["cli"], x["profile"]) for x in out["shared"])
    for cli, prof in sorted((merged.get("default_profile") or {}).items()):
        if prof == "@default" or ("%s%s" % (cli, prof)) in shared:
            out["defaults"].append((cli, prof))
        elif cli not in clis:
            out["defaults_skipped"].append((cli, prof, "%s is not in this repository's [agents] supported" % cli))
        else:
            out["defaults_skipped"].append((cli, prof, "%s %s is not shared (host_profile_names, or no such "
                                            "ak profile on the host)" % (cli, prof)))
    return out


def _write_private(path, text):
    d = os.path.dirname(path)
    old = os.umask(0o077)
    try:
        os.makedirs(d, 0o700, exist_ok=True)
    finally:
        os.umask(old)
    if os.path.islink(d) or not os.path.isdir(d) or os.stat(d).st_uid != os.getuid():
        raise HostAgentsError("%s is not a directory you own; refusing to write there" % d)
    os.chmod(d, 0o700)
    tmp = "%s.tmp-%d" % (path, os.getpid())
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.replace(tmp, path)


def _remove(path):
    try:
        if os.path.islink(path) or os.path.isfile(path):
            os.unlink(path)
    except OSError:
        pass


def _remove_env(project, env):
    """Remove the env file and its (then empty) directory."""
    _remove(env_file_path(project, env))
    d = env_dir_path(project, env)
    try:
        if os.path.isdir(d) and not os.path.islink(d):
            os.rmdir(d)
    except OSError:
        pass


def _bind(source, target, read_only):
    lines = ["      - type: bind",
             "        source: %s" % json.dumps(source.replace("$", "$$")),
             "        target: %s" % json.dumps(target)]
    if read_only:
        lines.append("        read_only: true")
    lines += ["        bind:", "          create_host_path: false"]
    return lines


def write(merged, service, project, out_path, env=None):
    """Write (or remove) the runtime overlay and the env file. Returns the plan
    without its values."""
    env = os.environ if env is None else env
    p = plan(merged, env)
    env_path = env_file_path(project, env)
    values = p.pop("values")
    _remove(legacy_env_file_path(project, env))
    if not p["enabled"] or not (p["shared"] or p["codex"] or p["env_names"]):
        _remove(out_path)
        _remove_env(project, env)
        return p
    if any(ord(c) < 32 for c in service) or not re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$", service):
        raise HostAgentsError("invalid service name %r" % service)
    for item in p["shared"] + ([p["codex"]] if p["codex"] else []):
        if any(ord(c) < 32 for c in item["source"]):
            raise HostAgentsError("refusing a host path with control characters")
    environment, volumes = [], []
    if p["shared"]:
        environment.append(("AGENTKIT_PROFILES_DIR", p["container_profiles"]))
        environment.append(("DCK_HOST_PROFILES", " ".join(shared_clis(p))))
        for s in p["shared"]:
            volumes += _bind(s["source"], s["target"], s["mode"] == "ro")
    for cli, prof in p["defaults"]:
        environment.append(("AGENTKIT_DEFAULT_PROFILE_%s" % cli.upper(), prof))
    if p["codex"]:
        environment.append(("DCK_HOST_CODEX", p["codex"]["target"]))
        volumes += _bind(p["codex"]["source"], p["codex"]["target"], p["codex"]["mode"] == "ro")
    if p["env_names"]:
        parent = os.path.dirname(os.path.dirname(env_path))
        if os.path.islink(parent) or (os.path.isdir(parent) and os.stat(parent).st_uid != os.getuid()):
            raise HostAgentsError("%s is not a directory you own; refusing to write there" % parent)
        _write_private(env_path, "# Generated by dck from the host's ak env file — do not edit.\n"
                       "# Only the Claude tokens of the shared profiles and [agents] host_env_keys.\n"
                       + "".join("%s='%s'\n" % (k, values[k]) for k in p["env_names"]))
        environment.append(("AGENTKIT_ENV", p["container_env"]))
        volumes += _bind(os.path.dirname(env_path), p["container_env_dir"], MOUNT_MODES["env"][0] == "ro")
    else:
        _remove_env(project, env)
    lines = ["# Generated by dck at runtime for [agents] host_profiles — never written into",
             "# the repository. Names host paths only; no value is in this file.",
             "# Shared profiles: %s" % (" ".join(profile_refs(p)) or "none"),
             "# Env file names (values only in the 0600 env file): %s" % (" ".join(p["env_names"]) or "none"),
             "services:", "  %s:" % service, "    environment:"]
    lines += ["      %s: %s" % (k, json.dumps(v)) for k, v in environment]
    lines.append("    volumes:")
    lines += volumes
    _write_private(out_path, "\n".join(lines) + "\n")
    return p


def shared_clis(p):
    out = []
    for s in p["shared"]:
        if s["cli"] not in out:
            out.append(s["cli"])
    return out


def profile_refs(p):
    """The shared profiles as "cli@name" (the Codex home is codex@default)."""
    refs = ["%s@%s" % (s["cli"], s["profile"][1:]) for s in p["shared"]]
    if p["codex"]:
        refs.append("codex@default")
    return refs


def ak_profiles(env=None, timeout=10):
    """`ak profiles --json` (profiles-v1) from the host's ak, or None."""
    env = os.environ if env is None else env
    try:
        r = subprocess.run(["ak", "profiles", "--json"], stdout=subprocess.PIPE,
                           stderr=subprocess.DEVNULL, timeout=timeout, text=True, env=dict(env))
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode != 0:
        return None
    try:
        doc = json.loads(r.stdout)
    except ValueError:
        return None
    if not isinstance(doc, dict) or doc.get("schema") != PROFILES_SCHEMA or not isinstance(doc.get("profiles"), list):
        return None
    return [x for x in doc["profiles"] if isinstance(x, dict)]


def report(merged, env=None, profiles=None):
    """Doctor lines: (level, message) with names only. `profiles` is the
    profiles-v1 list (None: ask the host's ak)."""
    env = os.environ if env is None else env
    p = plan(merged, env)
    p.pop("values")
    out = []
    if not p["enabled"]:
        out.append(("info", "host profiles: %s" % p["reason"]))
        return out, p
    if p["selected"]:
        out.append(("info", "host profiles: limited to host_profile_names: %s" % ", ".join(p["selected"])))
    if p["defaults"]:
        out.append(("info", "host profiles: default profile inside (AGENTKIT_DEFAULT_PROFILE_<CLI>, ak v0.5.2+): %s"
                    % ", ".join("%s %s" % d for d in p["defaults"])))
        out.append(("info", "host profiles: @default stays the container's own account (ak usage lists it; "
                    "ak <cli> @default uses its own home). A bare ak <cli> uses the profile above; "
                    "a plain claude/codex (a pane Herdr restores without ak) uses @default, not that profile"))
    for cli, prof, why in p["defaults_skipped"]:
        out.append(("warn", "host profiles: default_profile %s = %s not applied — %s" % (cli, prof, why)))
    out.append(("info", "host profiles: shared: %s" % (", ".join(profile_refs(p)) or "none")))
    for s in p["shared"]:
        out.append(("info", "host profiles: %s@%s %s — %s" % (s["cli"], s["profile"][1:], s["mode"], s["why"])))
    if p["codex"]:
        out.append(("info", "host profiles: codex@default (the host's Codex home) %s — %s"
                    % (p["codex"]["mode"], p["codex"]["why"])))
    for cli, why in p["skipped"]:
        if cli == "codex" and p["codex"]:
            why += "; the Codex home is shared"
        out.append(("info", "host profiles: %s ak profiles not shared — %s" % (cli, why)))
    out.append(("info", "host profiles: env file (%s) names: %s"
                % (MOUNT_MODES["env"][0], ", ".join(p["env_names"]) or "none")))
    for name, why in p["env_skipped"]:
        if name == "CLAUDE_CODE_OAUTH_TOKEN" and why == "not set on the host" and \
                any(c == "claude" for c, _ in p["defaults"]):
            out.append(("info", "host profiles: claude @default is not portable (macOS keychain); a bare "
                        "`ak claude` inside uses default_profile claude = %s"
                        % dict(p["defaults"]).get("claude")))
            continue
        if name == "CLAUDE_CODE_OAUTH_TOKEN" and why == "not set on the host":
            # Claude's own home is never shared: on macOS its login lives in the
            # keychain, so this token is the only way the default account gets in.
            out.append(("info", "host profiles: claude @default will not be logged in inside — its host "
                        "login (~/.claude, the macOS keychain) is never shared and CLAUDE_CODE_OAUTH_TOKEN "
                        "is not set on the host. Run `claude setup-token` for that account and store it in "
                        "ak's env file (~/.config/agentkit/env, or `ak env import <file>`) as "
                        "CLAUDE_CODE_OAUTH_TOKEN, then dck up; or log in once inside (`ak claude`), which "
                        "the container's claude volume keeps across recreates; or set [agents] default_profile = { claude = "
                        "\"@<a shared profile>\" } in the host profile"))
            continue
        out.append(("warn" if why != "not set on the host" else "info",
                    "host profiles: %s not copied — %s" % (name, why)))
    if profiles is None:
        profiles = ak_profiles(env)
    if profiles is None:
        out.append(("info", "host profiles: the host's `ak profiles --json` (%s) is unavailable; "
                    "logins not checked" % PROFILES_SCHEMA))
        return out, p
    names, refs = set(p["env_names"]), set(profile_refs(p))
    for row in profiles:
        cli, prof = row.get("cli"), str(row.get("profile") or "@default")
        ref = "%s@%s" % (cli, prof.lstrip("@") or "default")
        if ref not in refs and not (cli == "claude" and prof == "@default" and "CLAUDE_CODE_OAUTH_TOKEN" in names):
            continue
        label = "%s %s" % (cli, prof)
        if cli == "claude" and row.get("login") == "keychain":
            var = claude_token_var(prof)
            if var not in names:
                out.append(("warn", "host profiles: %s logs in through the macOS keychain, which a "
                            "container cannot read; run `claude setup-token` for that account, then "
                            "store it in ak's env file (~/.config/agentkit/env, or `ak env import <file>`) as %s"
                            % (label, var)))
                continue
        out.append(("info", "host profiles: %s (login: %s)" % (label, row.get("login") or "none")))
    return out, p
