# shellcheck shell=bash
#
# lib/hostlistener.sh — the host as a mesh peer: dck's own loopback listener.
#
#   dck host listener enable    a user-level sshd on 127.0.0.1:<host.port> (default
#                               22033) that accepts ONLY the dck key, kept alive by
#                               a launchd agent (macOS); records [host] in the profile
#   dck host listener disable   stops it and removes its launchd agent and files
#   dck host listener status    plist, process, port and host key fingerprint
#
# Agents in dck containers reach agents on the host through it (dck herdr mesh
# pushes it as `dck-host`). It is opt-in: `dck setup` offers it once on a
# terminal, and nothing here runs otherwise. It widens trust on purpose: any
# process that can use the dck key through your ssh-agent (code in a running
# dck container, while the agent socket is mounted) can open a shell on this
# host as you. docs/SECURITY.md describes it and every way to turn it off.
#
# Test hooks: DCK_HOST_OS (uname -s), DCK_LAUNCHCTL, DCK_HOST_SSHD,
# DCK_LAUNCH_AGENTS_DIR, DCK_LISTENER_WAIT (seconds to wait for the port).

DCK_VERBS="$DCK_VERBS host "

HOSTL_LABEL="com.dailybothq.dck.host-listener"

hostl_paths() {
  HOSTL_DIR="${DCK_CONFIG_HOME:-${XDG_CONFIG_HOME:-$HOME/.config}/dck}/host-listener"
  HOSTL_CFG="$HOSTL_DIR/sshd_config"
  HOSTL_KEY="$HOSTL_DIR/ssh_host_ed25519_key"
  HOSTL_AUTH="$HOSTL_DIR/authorized_keys"
  HOSTL_LOG="$HOSTL_DIR/sshd.log"
  HOSTL_PID="$HOSTL_DIR/sshd.pid"
  HOSTL_PLIST="${DCK_LAUNCH_AGENTS_DIR:-$HOME/Library/LaunchAgents}/$HOSTL_LABEL.plist"
  HOSTL_LAUNCHCTL="${DCK_LAUNCHCTL:-launchctl}"
  HOSTL_SSHD="${DCK_HOST_SSHD:-/usr/sbin/sshd}"
  HOSTL_DOMAIN="gui/$(id -u)"
}

# The profile's host settings (no repository needed): DCK_HOST_*, DCK_SSH_IDENTITY.
hostl_load_profile() {
  local args=(config host) line k v
  [ -n "${DCK_PROFILE_NAME:-}" ] && args+=(--profile "$DCK_PROFILE_NAME")
  local out
  out="$(dckpy "${args[@]}")" || exit "$DCK_EXIT_CONFIG"
  while IFS= read -r line; do
    k="${line%%=*}"; v="${line#*=}"
    case "$k" in
      DCK_HOST_MACHINE|DCK_HOST_LISTENER|DCK_HOST_PORT|DCK_HOST_KEY|DCK_HOST_LABEL|DCK_HOST_CONFIGURED|DCK_MESH_EXTERNAL|DCK_SSH_AUTHORIZED_EXTRA|DCK_SSH_IDENTITY)
        printf -v "$k" '%s' "$v"; export "${k?}" ;;
    esac
  done <<EOF
$out
EOF
}

hostl_is_macos() { [ "${DCK_HOST_OS:-$(uname -s)}" = "Darwin" ]; }

hostl_port_open() {
  # bash's /dev/tcp: no nc/lsof dependency.
  (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
}

hostl_profile_file() {
  local home="${DCK_CONFIG_HOME:-${XDG_CONFIG_HOME:-$HOME/.config}/dck}"
  if [ -n "${DCK_PROFILE_NAME:-}" ]; then
    printf '%s\n' "$home/profiles/$DCK_PROFILE_NAME.toml"
  else
    printf '%s\n' "$home/profile.toml"
  fi
}

# hostl_record_profile <true|false> — append a [host] table once (never edits
# an existing one: a profile that already has [host] is the user's decision).
hostl_record_profile() {
  local f
  f="$(hostl_profile_file)"
  if [ -f "$f" ] && grep -qE '^[[:space:]]*\[host\][[:space:]]*$' "$f"; then
    return 0
  fi
  (umask 077 && mkdir -p "$(dirname "$f")")
  {
    [ -s "$f" ] && printf '\n'
    printf '# Added by dck (host listener). See docs/config.md.\n[host]\nmachine = %s\n' "$1"
    [ "$1" = true ] && printf 'listener = "dck"\n'
  } >> "$f"
  note "profile: recorded [host] machine = $1 in $(pretty_path "$f")"
}

hostl_write_files() {
  local user port
  user="$(id -un)"
  port="${DCK_HOST_PORT:-22033}"
  [ "$port" != 0 ] || port=22033
  (umask 077 && mkdir -p "$HOSTL_DIR")
  chmod 700 "$HOSTL_DIR"
  if [ ! -f "$HOSTL_KEY" ]; then
    ssh-keygen -q -t ed25519 -N '' -C "dck-host-listener@$(hostname 2>/dev/null || echo host)" -f "$HOSTL_KEY" </dev/null >/dev/null \
      || die "could not generate the listener's host key"
    note "host listener: created its host key $(pretty_path "$HOSTL_KEY").pub"
  fi
  [ -f "$DCK_SSH_IDENTITY.pub" ] || die "$DCK_EXIT_CONFIG" "the dck key $(pretty_path "$DCK_SSH_IDENTITY").pub is missing — run: dck setup"
  # Only the dck key: the one your agents' containers use for the mesh.
  (umask 077 && cp "$DCK_SSH_IDENTITY.pub" "$HOSTL_AUTH.tmp" && mv "$HOSTL_AUTH.tmp" "$HOSTL_AUTH")
  (umask 077 && cat > "$HOSTL_CFG.tmp" <<EOF
# Generated by devcontainer-kit (dck host listener). Do not edit: re-run
# \`dck host listener enable\` to rewrite it, \`dck host listener disable\` to remove it.
Port $port
ListenAddress 127.0.0.1
HostKey $HOSTL_KEY
PidFile $HOSTL_PID
AuthorizedKeysFile $HOSTL_AUTH
AllowUsers $user
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
UsePAM no
PrintMotd no
AllowTcpForwarding no
AllowStreamLocalForwarding yes
PermitTunnel no
X11Forwarding no
Subsystem sftp internal-sftp
EOF
  ) && mv "$HOSTL_CFG.tmp" "$HOSTL_CFG"
  "$HOSTL_SSHD" -t -f "$HOSTL_CFG" >/dev/null 2>&1 || die "the listener's sshd configuration does not validate ($HOSTL_SSHD -t -f $HOSTL_CFG)"
  mkdir -p "$(dirname "$HOSTL_PLIST")"
  cat > "$HOSTL_PLIST.tmp" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$HOSTL_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$HOSTL_SSHD</string>
    <string>-D</string>
    <string>-f</string>
    <string>$HOSTL_CFG</string>
    <string>-E</string>
    <string>$HOSTL_LOG</string>
  </array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
</dict>
</plist>
EOF
  mv "$HOSTL_PLIST.tmp" "$HOSTL_PLIST"
  HOSTL_PORT="$port"
}

hostl_enable() {
  hostl_is_macos || die "$DCK_EXIT_ENV" "the dck host listener is macOS-only (the mesh needs Docker Desktop); on Linux use listener = \"remote-login\" or \"external\" in your profile"
  [ "${DCK_HOST_LISTENER:-dck}" = dck ] || die "$DCK_EXIT_CONFIG" "your profile sets [host] listener = \"$DCK_HOST_LISTENER\"; dck runs no listener for it"
  command -v ssh-keygen >/dev/null 2>&1 || die "$DCK_EXIT_ENV" "ssh-keygen is not on PATH"
  dck_identity_ensure
  hostl_write_files
  "$HOSTL_LAUNCHCTL" bootout "$HOSTL_DOMAIN/$HOSTL_LABEL" >/dev/null 2>&1 || true
  "$HOSTL_LAUNCHCTL" bootstrap "$HOSTL_DOMAIN" "$HOSTL_PLIST" >/dev/null 2>&1 \
    || die "launchctl could not load $(pretty_path "$HOSTL_PLIST")"
  local i=0 wait="${DCK_LISTENER_WAIT:-10}"
  while [ "$i" -lt "$wait" ] && ! hostl_port_open "$HOSTL_PORT"; do sleep 1; i=$((i + 1)); done
  if hostl_port_open "$HOSTL_PORT"; then
    note "host listener: answering on 127.0.0.1:$HOSTL_PORT (only the dck key; launchd keeps it running)"
  else
    warn "host listener: loaded, but 127.0.0.1:$HOSTL_PORT is not answering yet (log: $(pretty_path "$HOSTL_LOG"))"
  fi
  [ "${DCK_HOST_CONFIGURED:-0}" = 1 ] || hostl_record_profile true
  note "host listener: containers learn about it on their next dck up (or: dck herdr mesh)"
}

hostl_disable() {
  hostl_paths
  "$HOSTL_LAUNCHCTL" bootout "$HOSTL_DOMAIN/$HOSTL_LABEL" >/dev/null 2>&1 || true
  local f removed=""
  for f in "$HOSTL_PLIST" "$HOSTL_CFG" "$HOSTL_AUTH" "$HOSTL_KEY" "$HOSTL_KEY.pub" "$HOSTL_PID" "$HOSTL_LOG"; do
    if [ -e "$f" ]; then rm -f "$f"; removed="$removed $(pretty_path "$f")"; fi
  done
  rmdir "$HOSTL_DIR" 2>/dev/null || true
  if [ -n "$removed" ]; then
    note "host listener: stopped and removed:$removed"
  else
    note "host listener: not installed"
  fi
  note "host listener: set [host] machine = false in your profile to stop pushing the host to containers"
}

hostl_status() {
  note "listener kind    ${DCK_HOST_LISTENER:-dck} (profile [host] listener)"
  note "host as a peer   $([ "${DCK_HOST_MACHINE:-0}" = 1 ] && echo yes || echo no) (profile [host] machine)"
  if [ "${DCK_HOST_LISTENER:-dck}" != dck ]; then
    note "port             ${DCK_HOST_PORT:-?} ($(hostl_port_open "${DCK_HOST_PORT:-0}" && echo answering || echo "not answering"))"
    note "host key         ${DCK_HOST_KEY:-?}"
    return 0
  fi
  local port="${DCK_HOST_PORT:-22033}" loaded="no"
  [ "$port" != 0 ] || port=22033
  note "launchd agent    $([ -f "$HOSTL_PLIST" ] && pretty_path "$HOSTL_PLIST" || echo absent)"
  if [ -f "$HOSTL_PLIST" ] && "$HOSTL_LAUNCHCTL" print "$HOSTL_DOMAIN/$HOSTL_LABEL" >/dev/null 2>&1; then loaded="yes"; fi
  note "loaded           $loaded"
  note "port             127.0.0.1:$port ($(hostl_port_open "$port" && echo answering || echo "not answering"))"
  if [ -f "$HOSTL_KEY.pub" ]; then
    note "host key         $(ssh-keygen -lf "$HOSTL_KEY.pub" 2>/dev/null | awk '{print $2}')"
  else
    note "host key         absent — run: dck host listener enable"
  fi
}

# dck_host_listener_offer — called by `dck setup`: on a terminal, ask once
# whether to run the listener, and record the answer in the profile.
dck_host_listener_offer() {
  [ "${DCK_HOST_CONFIGURED:-0}" = 1 ] && return 0
  hostl_is_macos || return 0
  command -v herdr >/dev/null 2>&1 || return 0
  local ans="${DCK_HOST_LISTENER_ANSWER:-}"
  if [ -z "$ans" ]; then
    if [ -t 0 ] && [ "${DCK_NONINTERACTIVE:-0}" != "1" ] && { : </dev/tty; } 2>/dev/null; then
      printf '%s\n' \
        "dck: agents inside your containers can reach and answer the agents on this Mac through a" \
        "     loopback-only listener that accepts only the dck key. While it runs, code in any dck" \
        "     container (which can use that key through your ssh-agent) can open a shell here as you." >&2
      printf 'dck: enable the dck host listener? [Y/n] ' >&2
      read -r ans </dev/tty || ans=n
    else
      note "setup: to let agents in containers reach this host: dck host listener enable (docs/herdr.md)"
      return 0
    fi
  fi
  case "$ans" in
    n|N|no|NO) hostl_record_profile false; note "setup: host listener declined (dck host listener enable turns it on later)" ;;
    *) hostl_paths; hostl_enable ;;
  esac
}

dck_cmd_host() {
  local sub="${1:-}" action="${2:-}"
  if [ "$sub" = peers ] && [ $# -eq 2 ]; then
    case "$action" in
      install) dck_host_peers_install; return $? ;;
      status) dck_host_peers_status; return 0 ;;
    esac
  fi
  [ "$sub" = listener ] || die "$DCK_EXIT_USAGE" "usage: dck host listener enable|disable|status | dck host peers install|status"
  [ $# -eq 2 ] || die "$DCK_EXIT_USAGE" "usage: dck host listener enable|disable|status"
  hostl_load_profile
  hostl_paths
  case "$action" in
    enable) hostl_enable ;;
    disable) hostl_disable ;;
    status) hostl_status ;;
    *) die "$DCK_EXIT_USAGE" "usage: dck host listener enable|disable|status" ;;
  esac
}
