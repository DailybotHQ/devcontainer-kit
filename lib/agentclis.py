"""The coding-agent CLIs of one developer's image (v0.3.6).

dck.toml `[agents] supported` is what every image is WIRED for (the home volumes
and host-profile sharing of each supported CLI, installed or not); `[agents] clis`
is what is installed by default. Each developer chooses what THEIR image installs:
DCK_AGENT_CLIS or INSTALL_<CLI>_CLI=true in the environment or docker/local/.env,
or `[agents] clis` / `clis_extra` in the host profile (config.effective_clis has
the precedence). The rendered compose passes them as build args; `dck up` and
`dck rebuild` set DCK_AGENT_CLIS to the effective list.

When that list differs from dck.toml's, this runtime overlay (never written into
the repository) repeats it as the build arg: it reaches a compose file rendered
before v0.3.6, and an empty list ([agents] clis = [] in the host profile), which
compose's ${DCK_AGENT_CLIS:-...} would replace with dck.toml's.
"""

import json
import os
import re

import hostagents

# Where the agents layer records the CLIs it installed (lib/layers/agents.sh).
IMAGE_RECORD = "/opt/dck/agent-clis"


def plan(merged):
    repo = list(merged.get("agents.clis") or [])
    eff = list(merged.get("clis_effective") or [])
    return {"enabled": bool(merged.get("layers.agents")), "repo": repo, "effective": eff,
            "source": merged.get("clis_source") or "repo",
            "differs": bool(merged.get("layers.agents")) and eff != repo,
            "supported": list(merged.get("clis_supported") or [])}


def write(merged, service, out_path):
    """Write the overlay when the developer's list differs from the repository's,
    remove it otherwise. Returns the plan."""
    p = plan(merged)
    if not p["differs"]:
        try:
            if os.path.islink(out_path) or os.path.isfile(out_path):
                os.unlink(out_path)
        except OSError:
            pass
        return p
    if not re.match(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$", service):
        raise hostagents.HostAgentsError("invalid service name %r" % service)
    space = " ".join(p["effective"])
    lines = ["# Generated by dck at runtime for this developer's coding-agent CLIs — never",
             "# written into the repository. dck.toml [agents] clis: %s; effective (%s): %s"
             % (" ".join(p["repo"]) or "none", p["source"], space or "none"),
             "services:", "  %s:" % service,
             "    build:", "      args:", "        DCK_AGENT_CLIS: %s" % json.dumps(space)]
    hostagents._write_private(out_path, "\n".join(lines) + "\n")
    return p
